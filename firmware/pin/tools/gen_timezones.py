#!/usr/bin/env python3
"""Generate main/timezones.c: IANA time zone names (what PluralKit stores,
e.g. "Asia/Hong_Kong") -> POSIX TZ strings (what the pin's C library
understands, e.g. "HKT-8").

Reads this computer's time zone database (/usr/share/zoneinfo): every TZif
file ends with its POSIX string. Run again to pick up newer rules:
    python3 tools/gen_timezones.py
"""
import os
import sys

ZONEINFO = "/usr/share/zoneinfo"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main", "timezones.c")
SKIP_DIRS = {"posix", "right"}


def posix_string(path):
    with open(path, "rb") as f:
        data = f.read()
    if not data.startswith(b"TZif") or not data.endswith(b"\n"):
        return None
    footer = data[data.rindex(b"\n", 0, len(data) - 1) + 1:-1]
    try:
        return footer.decode("ascii") or None
    except UnicodeDecodeError:
        return None


zones = {}
for root, dirs, files in os.walk(ZONEINFO):
    rel_root = os.path.relpath(root, ZONEINFO)
    dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
    for name in files:
        rel = os.path.normpath(os.path.join(rel_root, name))
        if rel in ("posixrules", "localtime", "Factory") or not name[0].isupper():
            continue
        tz = posix_string(os.path.join(root, name))
        if tz:
            zones[rel] = tz
if "UTC" not in zones:
    sys.exit("no zones found - is " + ZONEINFO + " there?")


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '\\0"'


lines = [f"    {c_string(name)} {c_string(zones[name])}" for name in sorted(zones)]
with open(OUT, "w") as f:
    f.write(f"""/*
 * Time zone names -> POSIX TZ strings ({len(zones)} zones), generated by
 * tools/gen_timezones.py from the IANA time zone database. Don't edit by hand.
 */

#include <string.h>
#include "timezones.h"

/* "name\\0posix\\0" pairs, sorted by name */
static const char table[] =
""")
    f.write("\n".join(lines))
    f.write(""";

const char *timezones_posix(const char *name)
{
    for (const char *p = table; p < table + sizeof(table) - 1; ) {
        const char *posix = p + strlen(p) + 1;
        if (strcmp(p, name) == 0) {
            return posix;
        }
        p = posix + strlen(posix) + 1;
    }
    return NULL;
}
""")
print(f"{len(zones)} zones -> {os.path.normpath(OUT)}")
